#!/usr/bin/env python3
"""fake_registry.py — a local, dependency-free stand-in for npm / PyPI /
RubyGems that lets you validate dependency confusion WITHOUT uploading
anything to a real registry. EDUCATIONAL / AUTHORIZED-TESTING USE ONLY.

The attack it simulates: an unregistered package name that a victim repo
references. On the real registry, an attacker would claim the name; here,
YOU point the victim's package manager at this server instead, and it
serves whatever name is requested — generated on the fly, carrying a
harmless marker payload. If the victim's install/build pulls the name
from this server and the marker file appears, the confusion flow is
proven end-to-end: registry resolution really does deliver attacker
code into that build.

What it serves (one port, all three registries):

  npm        GET /<name>                        dynamic packument
             GET /__tarball/<name>              generated package tarball
                                               (preinstall -> marker)
  PyPI       GET /simple/<name>/                PEP 503 index page
             GET /__sdist/<file>                generated sdist
                                               (setup.py -> marker)
  RubyGems   GET /specs.4.8.gz, /latest_specs.4.8.gz,
             /prerelease_specs.4.8.gz           Marshal index (ruby-built)
             GET /gems/<file>.gem               generated gem
             GET /quick/Marshal.4.8/<spec>      gemspec marshal
                                               (extconf.rb runs at install)

Every request is logged, and every package RESOLUTION (not just file
fetch) is highlighted:

  [npm ] resolved: <name>          <- the victim's build took the bait
  [pypi] resolved: <name>
  [gem ] resolved: <name>

Usage:

  python3 scripts/fake_registry.py --port 8080
  python3 scripts/fake_registry.py --gem-name internal-gem-name
  python3 scripts/fake_registry.py --marker-file /tmp/proof.txt

Gem caveat: RubyGems discovers names from a Marshal-encoded index, so gem
names must be declared up front (--gem-name, repeatable); npm and PyPI
names are served dynamically for ANY name the client asks about. The gem
side needs a local `ruby` (used only to build the Marshal blobs and the
.gem file); npm/PyPI sides are pure stdlib.

See poc_packages/README.md ("Validating dependency confusion locally")
for the per-registry victim-side commands and the registry-priority
scenarios worth testing.
"""
