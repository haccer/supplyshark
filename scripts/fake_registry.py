_artifact_cache = {}


import re as _re


def _norm(name):
    return _re.sub(r"[-_.]+", "-", name).lower()


def _cached(kind, name, builder):
    key = (kind, _norm(name))
    if key not in _artifact_cache:
        _artifact_cache[key] = builder()
    return _artifact_cache[key]


def npm_tarball(name: str) -> bytes:
    return _cached("npm", name, lambda: _npm_tarball(name))


def _manifest_from_tarball(path: str) -> str | None:
    try:
        with tarfile.open(path, "r:gz") as tar:
            member = tar.extractfile("package/package.json")
            if member:
                return member.read().decode("utf-8", "replace")
    except Exception:
        pass
    return None


def npm_manifest(name: str) -> dict:
    """The package.json served BOTH in the tarball and in the packument
    version object — npm reads bin (for linking) and scripts (for the
    install-scripts flow) from the packument, so omitting them there
    silently changes client behavior."""
    return {
        "name": name, "version": VERSION,
        "description": "fake-registry validation package (educational use only)",
        "bin": {name.split("/")[-1]: "index.js"},
        "scripts": {"preinstall": "node index.js"},
    }


def _npm_tarball(name: str) -> bytes:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        def add(path, data, mode=0o644):
            ti = tarfile.TarInfo(path)
            ti.size = len(data)
            ti.mode = mode
            tar.addfile(ti, io.BytesIO(data))
        add("package/package.json", json.dumps(npm_manifest(name), indent=2).encode())
        add("package/index.js", NPM_INDEX_JS.encode(), mode=0o755)
    return buf.getvalue()


def pypi_sdist(name: str) -> bytes:
    return _cached("sdist", name, lambda: _pypi_sdist(name))


def _pypi_sdist(name: str) -> bytes:
    normalized = name.replace("-", "_")
    root = f"{normalized}-{VERSION}"
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        def add(path, data):
            ti = tarfile.TarInfo(path)
            ti.size = len(data)
            tar.addfile(ti, io.BytesIO(data))
        add(f"{root}/PKG-INFO",
            f"Metadata-Version: 2.1\nName: {name}\nVersion: {VERSION}\n".encode())
        add(f"{root}/pyproject.toml",
            "[build-system]\nrequires = [\"setuptools>=61\"]\n"
            "build-backend = \"setuptools.build_meta\"\n".encode())
        add(f"{root}/setup.py", PYPI_SETUP.format(name=name, version=VERSION).encode())
        add(f"{root}/payload.py", PYPI_PAYLOAD.encode())
    return buf.getvalue()


def build_gem_file(name: str, workdir: str) -> str:
    """Generate + `gem build` a gem carrying the marker payload; returns
    the path to the .gem file."""
    lib_name = name.replace("-", "_")
    d = os.path.join(workdir, f"gem-{name}")
    os.makedirs(os.path.join(d, "lib"), exist_ok=True)
    os.makedirs(os.path.join(d, "ext"), exist_ok=True)
    with open(os.path.join(d, f"{lib_name}.gemspec"), "w") as f:
        f.write(GEMSPEC.format(name=name, version=VERSION))
    with open(os.path.join(d, "lib", f"{lib_name}.rb"), "w") as f:
        f.write(GEM_LIB)
    with open(os.path.join(d, "ext", "extconf.rb"), "w") as f:
        f.write(GEM_EXTCONF.format(lib_name=lib_name))
    gemfile = os.path.join(d, f"{name}-{VERSION}.gem")
    subprocess.run(["gem", "build", f"{lib_name}.gemspec"], cwd=d,
                   check=True, capture_output=True)
    return gemfile


def ruby_marshal_specs(names, prerelease=False):
    """specs.4.8 Marshal blob via the local ruby (python cannot produce
    Ruby Marshal). Layout: [[name, Gem::Version, platform, deps], ...]."""
    # specs.4.8 shape: [[name, Gem::Version, platform], ...] — three
    # elements exactly; a fourth breaks Gem::NameTuple.new(*tuple)
    entries = ", ".join(
        f"['{n}', Gem::Version.new('{VERSION}'), 'ruby']" for n in names)
    script = (f"require 'zlib'; require 'rubygems/version';"
              f"specs = [{entries}];"
              f"w = Zlib::GzipWriter.new(STDOUT);"
              f"w.write(Marshal.dump(specs)); w.close")
    out = subprocess.run(["ruby", "-e", script], check=True,
                         capture_output=True)
    return out.stdout


def ruby_marshal_gemspec(name):
    """quick/Marshal.4.8/*.gemspec.rz payload: Marshal of the spec INSIDE
    the built .gem (ground truth — a text-evaluated gemspec would resolve
    its Dir[] globs in the wrong cwd), RAW-DEFLATED: the client inflates
    with Zlib::Inflate, so gzip framing fails 'incorrect header check'."""
    gem_path = State.gem_files[name]
    script = (f"require 'zlib'; require 'rubygems/package';"
              f"s = Gem::Package.new({gem_path!r}).spec;"
              f"print Zlib::Deflate.deflate(Marshal.dump(s))")
    return subprocess.run(["ruby", "-e", script], check=True,
                          capture_output=True).stdout


class State:
    gem_names = []
    gem_files = {}
    marker_file = None
    custom_tarballs = {}


class Handler(BaseHTTPRequestHandler):
    server_version = "fake-registry/1.0"

    def log(self, msg):
        print(f"[fake-registry] {msg}", flush=True)

    def _send(self, code, body, ctype="application/octet-stream"):
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        try:
            self._route()
        except BrokenPipeError:
            pass

    def _route(self):
        path = urllib.parse.unquote(urllib.parse.urlparse(self.path).path)
        marker = State.marker_file

        # ---- npm: dynamic packument + generated tarball ----
        if path.startswith("/__tarball/"):
            name = path[len("/__tarball/"):]
            custom = State.custom_tarballs.get(name)
            if custom:
                self.log(f"[npm ] serving CUSTOM tarball for: {name}")
                with open(custom, "rb") as f:
                    return self._send(200, f.read(), "application/gzip")
            self.log(f"[npm ] serving tarball for: {name}")
            return self._send(200, npm_tarball(name), "application/gzip")
        if path.startswith("/simple/") and path.endswith("/"):
            return self._pypi_simple(path)
        if path.startswith("/__sdist/"):
            fname = path[len("/__sdist/"):]
            name = urllib.parse.unquote(fname).rsplit("-", 1)[0]
            self.log(f"[pypi] serving sdist for: {name}")
            return self._send(200, pypi_sdist(name), "application/gzip")
        if path in ("/specs.4.8.gz", "/latest_specs.4.8.gz", "/prerelease_specs.4.8.gz"):
            return self._gem_specs(path)
        if path.startswith("/gems/"):
            return self._gem_file(path[len("/gems/"):])
        if path.startswith("/quick/Marshal.4.8/"):
            fname = path.rsplit("/", 1)[-1]
            suffix = f"-{VERSION}.gemspec.rz"
            name = fname[: -len(suffix)] if fname.endswith(suffix) else fname
            self.log(f"[gem ] RESOLVED: {name} (quick spec)")
            return self._send(200, ruby_marshal_gemspec(name),
                              "application/octet-stream")
        # npm packument: /name or /@scope/name — anything else that looks
        # like a bare package path is treated as npm (it is the fallback
        # registry surface)
        is_scoped = path.count("/") == 2 and path.startswith("/@")
        is_plain = path.count("/") == 1
        if (is_scoped or is_plain) and not path.startswith("/-/") and path != "/":
            name = path.lstrip("/")
            if name and not name.startswith("__") and not name.startswith("-"):
                self.log(f"[npm ] RESOLVED: {name}")
                base = f"http://{self.headers.get('Host', '127.0.0.1')}"
                tgz = f"{base}/__tarball/{urllib.parse.quote(name, safe='')}"
                integ = "sha512-" + base64.b64encode(
                    hashlib.sha512(npm_tarball(name)).digest()).decode()
                custom = State.custom_tarballs.get(name)
                if custom:
                    with open(custom, "rb") as f:
                        data = f.read()
                    integ = "sha512-" + base64.b64encode(
                        hashlib.sha512(data).digest()).decode()
                    manifest = json.loads(
                        _manifest_from_tarball(custom) or "{}")
                    manifest.setdefault("name", name)
                    manifest.setdefault("version", VERSION)
                    manifest["dist"] = {"tarball": tgz, "integrity": integ}
                else:
                    manifest = npm_manifest(name)
                    manifest["dist"] = {"tarball": tgz, "integrity": integ}
                ver_key = manifest.get("version", VERSION)
                doc = {"name": name, "dist-tags": {"latest": ver_key},
                       "versions": {ver_key: manifest},
                       "time": {ver_key: "2026-01-01T00:00:00.000Z"}}
                return self._send(200, json.dumps(doc).encode(),
                                  "application/json")
        return self._send(404, b'{"error":"not found"}', "application/json")

    BUILD_TOOLS = {"setuptools", "wheel", "pip"}

    def _proxy_pypi(self, path):
        """Read-only relay of build-tool files from real PyPI (downloads
        only — this server never publishes anywhere)."""
        url = f"https://pypi.org{path}"
        try:
            import urllib.request
            with urllib.request.urlopen(url, timeout=20) as r:
                body = r.read()
                ctype = r.headers.get("Content-Type", "application/octet-stream")
        except Exception as e:
            self.log(f"[pypi] build-tool proxy failed for {path}: {e}")
            return self._send(404, b"proxy unavailable", "text/plain")
        self.log(f"[pypi] build-tool proxied: {path}")
        return self._send(200, body, ctype)

    def _pypi_simple(self, path):
        name = path[len("/simple/"):-1]
        if not name:
            return self._send(404, b"not found", "text/plain")
        if name.lower() in self.BUILD_TOOLS:
            return self._proxy_pypi(path)
        self.log(f"[pypi] RESOLVED: {name}")
        fname = f"{name.replace('-', '_')}-{VERSION}.tar.gz"
        sdist = pypi_sdist(name)
        sha = hashlib.sha256(sdist).hexdigest()
        html = (f'<!DOCTYPE html><html><body>'
                f'<a href="/__sdist/{urllib.parse.quote(fname)}#sha256={sha}">'
                f'{fname}</a></body></html>\n')
        return self._send(200, html.encode(), "text/html")

    def _gem_specs(self, path):
        if not State.gem_names:
            self.log("[gem ] index requested but no --gem-name declared: 404")
            return self._send(404, b"", "application/gzip")
        if path == "/prerelease_specs.4.8.gz":
            names = []  # stable names must not appear as prereleases
        else:
            names = State.gem_names
        self.log(f"[gem ] serving {path} for: {', '.join(names) or '(empty)'}")
        return self._send(200, ruby_marshal_specs(names),
                          "application/gzip")

    def _gem_file(self, fname):
        name = fname.rsplit("-", 1)[0]
        if name not in State.gem_files:
            self.log(f"[gem ] undeclared gem requested: {name} "
                     f"(pass --gem-name {name}); 404")
            return self._send(404, b"", "application/gzip")
        with open(State.gem_files[name], "rb") as f:
            return self._send(200, f.read(), "application/gzip")

    def log_message(self, fmt, *args):
        pass  # request line already contextualized by the handlers above


def main():
    ap = argparse.ArgumentParser(
        description="Local fake npm/PyPI/RubyGems registry for validating "
                    "dependency confusion without touching real registries. "
                    "Educational / authorized-testing use only.")
    ap.add_argument("--port", type=int, default=8080)
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--gem-name", action="append", default=[],
                    help="gem name to publish on the fake index (repeatable); "
                         "npm/PyPI names are served dynamically for any request")
    ap.add_argument("--marker-file",
                    help="where victim-side payloads write their proof "
                         "(default: fake-registry-proof.txt in the install cwd)")
    ap.add_argument("--tarball", action="append", default=[],
                    metavar="NAME:=PATH",
                    help="serve a researcher-built tarball (e.g. `npm pack` "
                         "output from poc_packages/npm/rce) under NAME "
                         "instead of the generated payload; repeatable")
    args = ap.parse_args()

    State.marker_file = args.marker_file
    State.gem_names = args.gem_name
    for spec in args.tarball:
        if ":=" not in spec:
            sys.exit(f"[!] --tarball expects NAME:=PATH, got {spec!r}")
        name, path = spec.split(":=", 1)
        if not os.path.isfile(path):
            sys.exit(f"[!] --tarball file not found: {path}")
        State.custom_tarballs[name] = os.path.abspath(path)
        print(f"[fake-registry] custom tarball: {name} -> {path}", flush=True)

    workdir = tempfile.mkdtemp(prefix="fake-registry-")
    for name in args.gem_name:
        try:
            State.gem_files[name] = build_gem_file(name, workdir)
            print(f"[fake-registry] built gem: {name}", flush=True)
        except FileNotFoundError:
            sys.exit("[!] 'gem'/'ruby' not found: gem names require a local "
                     "ruby toolchain; drop --gem-name or install ruby")
        except subprocess.CalledProcessError as e:
            sys.exit(f"[!] gem build failed for {name}: {e.stderr[:200]!r}")

    print(f"[fake-registry] listening on http://{args.host}:{args.port}")
    print("[fake-registry] npm:   npm install <name> --registry "
          f"http://{args.host}:{args.port}")
    print("[fake-registry] pypi:  pip install <name> --index-url "
          f"http://{args.host}:{args.port}/simple/ --no-deps")
    print("[fake-registry] gem:   gem install <name> --clear-sources --source "
          f"http://{args.host}:{args.port} "
          "(names must be passed via --gem-name)")
    if args.marker_file:
        print(f"[fake-registry] marker file: {args.marker_file}")
    ThreadingHTTPServer((args.host, args.port), Handler).serve_forever()


if __name__ == "__main__":
    main()
